-- Customer Insights Dashboard assessment database, version 1.0.
-- PostgreSQL 16+. No extensions are required. Use a dedicated assessment database.
-- Repeatable initialisation; this is not a migration tool for an unrelated schema.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS public.customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    email text NOT NULL,
    company text,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customers_id_positive CHECK (id > 0),
    CONSTRAINT customers_name_not_blank CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT customers_email_not_blank CHECK (length(btrim(email)) > 0),
    CONSTRAINT customers_company_not_blank CHECK (company IS NULL OR length(btrim(company)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS customers_email_lower_uq
    ON public.customers (lower(email));

CREATE TABLE IF NOT EXISTS public.staff (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    email text NOT NULL,
    role text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT staff_id_positive CHECK (id > 0),
    CONSTRAINT staff_name_not_blank CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT staff_email_not_blank CHECK (length(btrim(email)) > 0),
    CONSTRAINT staff_role_not_blank CHECK (length(btrim(role)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS staff_email_lower_uq
    ON public.staff (lower(email));

CREATE TABLE IF NOT EXISTS public.deals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL,
    staff_id integer,
    product_category text COLLATE "C" NOT NULL,
    deal_value numeric(12, 2) NOT NULL,
    status text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT deals_id_positive CHECK (id > 0),
    CONSTRAINT deals_customer_fk FOREIGN KEY (customer_id)
        REFERENCES public.customers (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT deals_staff_fk FOREIGN KEY (staff_id)
        REFERENCES public.staff (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT deals_category_allowed CHECK (product_category IN (
        'Dining', 'Events', 'Experiences', 'Luxury Goods', 'Travel', 'Wellness'
    )),
    CONSTRAINT deals_value_range CHECK (deal_value BETWEEN 0 AND 9999999999.99),
    CONSTRAINT deals_status_allowed CHECK (status IN ('pending', 'completed', 'cancelled'))
);

COMMENT ON TABLE public.customers IS 'Synthetic customer records for the developer assessment.';
COMMENT ON TABLE public.staff IS 'Synthetic staff records; job roles do not define application permissions.';
COMMENT ON TABLE public.deals IS 'Synthetic deals, linked to one customer and optionally one staff member.';
COMMENT ON COLUMN public.deals.deal_value IS 'GBP pounds, not pence; exact decimal with two fractional digits. Zero is valid.';
COMMENT ON COLUMN public.deals.created_at IS 'Deal creation instant, not a completion timestamp. Display in UTC.';
COMMENT ON COLUMN public.deals.staff_id IS 'NULL means no staff member is recorded on this deal. It does not define a customer owner.';
COMMENT ON COLUMN public.deals.status IS 'Only the exact value completed contributes to purchase metrics.';
COMMENT ON COLUMN public.deals.product_category IS 'Canonical category label. C collation provides deterministic category tie ordering.';

-- Only primary-key and case-insensitive email uniqueness indexes are supplied.
-- Candidates may propose/add appropriate query indexes in their own migrations.
COMMIT;
